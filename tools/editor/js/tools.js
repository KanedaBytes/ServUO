// Creating records: the click-by-click tools, and the form that finishes each one.
//
// A tool collects geometry on the canvas, then a modal asks for the fields the geometry cannot
// supply. Nothing is validated for real here - validate.js previews and the shard decides - but
// the pickers are populated from the shapes already loaded, so a valid choice is the easy one.
//
// WHAT A TOOL IS: a data record, not an object with methods. `kind` names one of six behaviours
// and the state machine for all six lives in app.js. Adding a tool is a table entry; adding a new
// KIND is a change in three places, which is the right amount of friction for the difference.
//
// The ModernUO original's `route` and `point-then-route` kinds are gone rather than ported. They
// collected free polylines, and there is nothing in this schema to write one to: an edge's line is
// its two endpoints and a route's is its waypoint list. Their replacements collect ids instead.
//
// NO FIELD CARRIES ITS OWN LIST OF VALUES. A field names a key in the vocabulary
// (js/vocab.js -> /api/vocabulary) and the control is filled from that when the form opens.
// Before this, half these fields were free text with an example value typed into the table -
// `value: 'shop'` for a destination type, `'mine or lumber'` in a label - which is a copy of the
// shard's vocabulary that nothing checks and nothing updates. uo-offline has the same fault more
// visibly: a checked-in spawn_types.json regenerated by hand, and a literal behaviour array in
// the page (map-editor/map.html:204).
//
// SELECT ONLY WHERE THE SHARD HAS A CLOSED SET. Route mode, edge kind, spawner kind - those are
// C# enums and a value outside them is a file the shard refuses. Destination type, every tag
// field and the site type are `combo`, because NavRecords.cs deliberately makes them free tokens
// ("uo-offline-server's flat enum conflated category and mechanism; ours is a free token
// deliberately", ValidateDestinations) and a control stricter than the file format would stop
// you authoring a type the shard would have accepted. uo-offline reached the same answer for the
// same reason - map.html:126 is an <input list>, not a <select>.
//
// FIELD KEYS:
//   options      a literal closed list - only for sets that are not the shard's to change
//   optionsFrom  a vocabulary key; renders a <select> unless `combo` is set
//   combo        typeable: an <input list> over a generated <datalist>
//   dependsOn    another field's key; refill this one whenever that one changes
//   help         one line under the label saying what the field decides
//   list         a static datalist id in index.html (the id pickers, filled by fillLists)

