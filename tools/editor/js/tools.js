function finish(values) {
    dom.modal.hidden = true;

    const resolve = resolveForm;

    resolveForm = null;
    resolve?.(values);
}

/**
 * Opens the modal and resolves with the field values, or null if cancelled.
 *
 * Takes anything with a title and a list of fields, so it serves both the create tools and one-off
 * prompts like "go to coordinate" without a second dialog implementation.
 */
export function askFor(tool, defaults) {
    dom.title.textContent = tool.title;
    dom.ok.textContent = tool.submit || 'Create';
    dom.error.textContent = '';
    dom.fields.innerHTML = '';

    // Fields that another field drives, so a change can refill them without re-rendering the form
    // and losing what has already been typed into it.
    const dependents = [];

    for (const field of tool.fields) {
        const label = document.createElement('label');
        const caption = document.createElement('span');

        caption.textContent = field.label;

        let input;

        if (field.options || (field.optionsFrom && !field.combo)) {
            input = document.createElement('select');
            fillSelect(input, optionsOf(field, defaults));
        } else {
            input = document.createElement('input');
            input.type = field.checkbox ? 'checkbox' : 'text';
            input.autocomplete = 'off';

            if (field.list) {
                input.setAttribute('list', field.list);
            }

            // A combo is an <input list> over a datalist minted for this field. Its own element
            // rather than one of the shared ones in index.html, because a dependent list changes
            // as another field changes and a shared datalist would leak that into every form
            // using it.
            if (field.optionsFrom) {
                const datalist = document.createElement('datalist');

                datalist.id = `modal-list-${field.key}`;
                input.setAttribute('list', datalist.id);
                fillDatalist(datalist, optionsOf(field, defaults));
                label.append(datalist);
            }
        }

        input.name = field.key;
        input.dataset.label = field.label;

        const preset = defaults && field.key in defaults ? defaults[field.key] : field.value;

        if (preset !== undefined && preset !== null) {
            if (field.checkbox) {
                input.checked = preset === true || preset === 'true';
            } else {
                input.value = String(preset);
            }
        }

        if (field.required) {
            input.required = true;
        }

        label.append(caption, input);

        // The one line saying what the field decides. Under the control rather than in the label,
        // so the label stays scannable and the explanation is there when you stop on it.
        if (field.help) {
            const help = document.createElement('small');

            help.className = 'field-help';
            help.textContent = field.help;
            label.append(help);
        }

        dom.fields.append(label);

        if (field.dependsOn) {
            dependents.push(field);
        }
    }

    // Wired after every control exists, because a dependent may be declared before the field it
    // depends on.
    for (const field of dependents) {
        const driver = dom.fields.querySelector(`[name="${field.dependsOn}"]`);
        const target = dom.fields.querySelector(`[name="${field.key}"]`);

        if (!driver || !target) {
            continue;
        }

        driver.addEventListener('change', () => {
            const values = optionsOf(field, { [field.dependsOn]: driver.value });

            if (target.tagName === 'SELECT') {
                fillSelect(target, values);
                return;
            }

            fillDatalist(document.getElementById(`modal-list-${field.key}`), values);

            // A type from the previous kind is not a type of this one. Cleared rather than left,
            // because a stale value that no longer appears in the list is exactly the thing that
            // gets saved by accident.
            const plain = values.map((v) => (typeof v === 'string' ? v : v.value));

            if (target.value && !plain.includes(target.value)) {
                target.value = '';
            }
        });
    }

    dom.modal.hidden = false;
    dom.fields.querySelector('[name]')?.focus();

    return new Promise((resolve) => {
        resolveForm = resolve;
    });
}

/**
 * The values a field offers right now.
 *
 * `filter` lets a field narrow the vocabulary by another field's current value - the spawner's
 * type list is the vocabulary's `spawnTypes` for whichever kind is selected.
 */
function optionsOf(field, values) {
    if (field.options) {
        return field.options.slice();
    }

    if (!field.optionsFrom) {
        return [];
    }

    if (typeof field.optionsFrom === 'function') {
        return field.optionsFrom(vocab, values || {});
    }

    return vocab.optionsFor(field.optionsFrom);
}

function fillSelect(select, values) {
    select.innerHTML = '';

    for (const value of values) {
        const option = document.createElement('option');

        // A value may be a bare string or a {value, label} pair - the spawner's kinds carry their
        // type count in the label, which is how an empty bucket is visible in the form rather
        // than looking like a list that has not loaded.
        option.value = typeof value === 'string' ? value : value.value;
        option.textContent = typeof value === 'string' ? value : value.label;
        select.append(option);
    }
}

function fillDatalist(datalist, values) {
    if (!datalist) {
        return;
    }

    datalist.innerHTML = '';

    for (const value of values) {
        const option = document.createElement('option');

        option.value = typeof value === 'string' ? value : value.value;
        datalist.append(option);
    }
}

export function showModalError(message) {
    dom.error.textContent = message;
}

/** Fills the id pickers from the shapes already loaded. */
export function fillLists(shapes) {
    const of = (prefix) => shapes
        .filter((shape) => shape.id.startsWith(prefix + ':'))
        .map((shape) => shape.id.slice(prefix.length + 1));

    const waypoints = of('wp');
    const destinations = of('dest');

    fill('waypoint-list', waypoints);
    fill('destination-list', destinations);
    fill('route-list', of('route'));

    // Anything a daily-life field may name: Nav.TryRoute takes either, and so does a shop or home.
    fill('navid-list', [...destinations, ...waypoints]);

    // The spawn-file and creature lists used to be derived here, from the spawn files loaded and
    // from every <Objects2> entry already on the map. Both now come from the vocabulary instead
    // (js/vocab.js): the files from the directory rather than from whichever ones the viewport
    // happened to load, and the types from what the shard actually has a constructable class for
    // rather than from what is already spawning - which could never suggest a type nobody had
    // used yet, and could happily suggest one that no longer compiles.
}

function fill(id, values) {
    const list = document.getElementById(id);

    if (!list) {
        return;
    }

    list.innerHTML = '';

    for (const value of values) {
        const option = document.createElement('option');

        option.value = value;
        list.append(option);
    }
}
